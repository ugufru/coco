"""Yoda in SG6 semigraphics, poke-ready for the CoCo terminal (#573).

CORRECTION (2026-10-12, #573): the red/orange palette below came from a
flawed probe that used solid blocks, which look the same in SG4 and SG6.
The CoCo terminal runs on the CoCo 2B's MC6847T1, which has no SG6: with
lowercase on it stays in SG4, so these bytes come out scrambled there.
This script is only right on a plain-6847 CoCo with $FF22 bit 4 set, and
there bit 6 gives blue/red (CSS=0) or magenta/orange (CSS=1), not
red/orange. See coco-guides/vdg-modes.md, Semigraphics-6.

Two colours only: C1=1 orange (skin), C1=0 red (eyes, mouth, robe). Colour is
fixed per 2x3 cell, so every colour change in the art below lands on an even
column and a whole three-row band.
"""

BITS = {(0, 0): 32, (1, 0): 16, (0, 1): 8, (1, 1): 4, (0, 2): 2, (1, 2): 1}
C1 = dict(R=0, O=1)

ART = """
................OOOO................
..............OOOOOOOO..............
............OOOOOOOOOOOO............
..........OOOOOOOOOOOOOOOO..........
..........OOOOOOOOOOOOOOOO..........
..........OOOOOOOOOOOOOOOO..........
....OOOOOOOOOOOOOOOOOOOOOOOOOOOO....
..OOOOOOOOOOOOOOOOOOOOOOOOOOOOOOOO..
..OOOOOOOOOOOOOOOOOOOOOOOOOOOOOOOO..
....OOOOOOOOOOOOOOOOOOOOOOOOOOOO....
......OOOOOOOOOOOOOOOOOOOOOOOO......
........OOOOOOOOOOOOOOOOOOOO........
..........OORRRROOOORRRROO..........
..........OORRRROOOORRRROO..........
..........OORRRROOOORRRROO..........
..........OOOOOORRRROOOOOO..........
..........OOOOOORRRROOOOOO..........
..........OOOOOORRRROOOOOO..........
............OOOOOOOOOOOO............
............OOOOOOOOOOOO............
..............OOOOOOOO..............
..............RRRRRRRR..............
..........RRRRRRRRRRRRRRRR..........
........RRRRRRRRRRRRRRRRRRRR........
......RRRRRRRRRRRRRRRRRRRRRRRR......
......RRRRRRRRRRRRRRRRRRRRRRRR......
......RRRRRRRRRRRRRRRRRRRRRRRR......
....RRRRRRRRRRRRRRRRRRRRRRRRRRRR....
....RRRRRRRRRRRRRRRRRRRRRRRRRRRR....
....RRRRRRRRRRRRRRRRRRRRRRRRRRRR....
....RRRRRRRRRRRRRRRRRRRRRRRRRRRR....
..RRRRRRRRRRRRRRRRRRRRRRRRRRRRRRRR..
..RRRRRRRRRRRRRRRRRRRRRRRRRRRRRRRR..
..RRRRRRRRRRRRRRRRRRRRRRRRRRRRRRRR..
..RRRRRRRRRRRRRRRRRRRRRRRRRRRRRRRR..
..RRRRRRRRRRRRRRRRRRRRRRRRRRRRRRRR..
""".strip().split("\n")

ORG_C, ORG_R = 7, 2                        # cell origin on the 32x16 screen

scr = [0x60] * 512                         # $60 is space in T1 codes
for cr in range(len(ART) // 3):
    for cc in range(len(ART[0]) // 2):
        pat, col = 0, 1
        for dy in range(3):
            for dx in range(2):
                ch = ART[cr * 3 + dy][cc * 2 + dx]
                if ch != '.':
                    pat |= BITS[(dx, dy)]
                    col = C1[ch]
        if pat:
            scr[(ORG_R + cr) * 32 + ORG_C + cc] = 0x80 | (col << 6) | pat

hexs = "".join("%02X" % b for b in scr)
for i in range(0, 512, 128):
    print(0x400 + i, hexs[i * 2:(i + 128) * 2])
